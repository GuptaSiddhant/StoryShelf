export function generateAwsQueue(): string {
  return `${header()}resource "aws_sqs_queue" "capture_dlq" {
  name = "\${var.project}-capture-dlq"
}

resource "aws_sqs_queue" "capture" {
  name                       = "\${var.project}-capture"
  visibility_timeout_seconds = 300
  redrive_policy = jsonencode({
    deadLetterTargetArn = aws_sqs_queue.capture_dlq.arn
    maxReceiveCount     = 3
  })
}
`;
}

export function generateAwsDatabase(dbEngine: "rds" | "dsql"): string {
  if (dbEngine === "dsql") {
    return `${header()}# Serverless Postgres. The server connects with
# createPostgresDatabase({ url: <cluster endpoint> }).
resource "aws_dsql_cluster" "main" {
  deletion_protection_enabled = true

  tags = { Name = "\${var.project}-db" }
}
`;
  }
  return `${header()}# VPC-isolated Postgres for regulated estates. The server connects with
# createPostgresDatabase({ url: <DATABASE_URL with sslmode=require> }).
resource "aws_db_subnet_group" "main" {
  name       = "\${var.project}-db"
  subnet_ids = data.aws_subnets.private.ids
}

resource "aws_db_instance" "main" {
  identifier             = "\${var.project}-db"
  engine                 = "postgres"
  engine_version         = "16"
  instance_class         = "db.t4g.micro"
  allocated_storage      = 20
  db_subnet_group_name   = aws_db_subnet_group.main.name
  vpc_security_group_ids = [aws_security_group.ecs.id]
  skip_final_snapshot    = true
}
`;
}

export function generateAwsIdentity(): string {
  return `${header()}# Cognito User Pool: the enterprise identity front door. Federate a
# corporate IdP (Entra/Okta) via SAML by setting var.saml_metadata_url.
resource "aws_cognito_user_pool" "main" {
  name = "\${var.project}-users"
}

resource "aws_cognito_user_pool_client" "shelf" {
  name            = "\${var.project}-shelf"
  user_pool_id    = aws_cognito_user_pool.main.id
  generate_secret = true

  allowed_oauth_flows                  = ["code"]
  allowed_oauth_scopes                 = ["openid", "email", "profile"]
  callback_urls                        = ["https://\${var.domain_name == "" ? aws_lb.main.dns_name : var.domain_name}/auth/callback"]
  supported_identity_providers         = ["COGNITO"]
}

resource "aws_cognito_user_group" "admins" {
  name         = "shelf-admins"
  user_pool_id = aws_cognito_user_pool.main.id
}

resource "aws_cognito_identity_provider" "saml" {
  count         = var.saml_metadata_url == "" ? 0 : 1
  user_pool_id  = aws_cognito_user_pool.main.id
  provider_name = "CorporateSAML"
  provider_type = "SAML"

  provider_details = {
    MetadataURL = var.saml_metadata_url
  }
}
`;
}

export function generateAwsCompute(): string {
  return `${header()}# ECS Fargate: long-lived app + worker services. Playwright/Chromium
# renders on Fargate — Lambda's 15-minute limit and /tmp caps rule it out.
resource "aws_lb" "main" {
  name               = "\${var.project}-alb"
  load_balancer_type = "application"
  security_groups    = [aws_security_group.alb.id]
  subnets            = data.aws_subnets.public.ids
}

resource "aws_ecs_cluster" "main" {
  name = "\${var.project}-cluster"
}

resource "aws_cloudwatch_log_group" "app" {
  name              = "/ecs/\${var.project}-app"
  retention_in_days = 30
}

resource "aws_cloudwatch_log_group" "worker" {
  name              = "/ecs/\${var.project}-worker"
  retention_in_days = 30
}
`;
}

