const AWS_FILES: ReadonlyArray<readonly [string, (options: AwsTerraformOptions) => string]> = [
  ["terraform/versions.tf", () => generateAwsVersions()],
  ["terraform/variables.tf", () => generateAwsVariables()],
  [
    "terraform/network.tf",
    () => `${generateAwsVpc()}${generateAwsSecurity()}${generateAwsEndpoints()}`,
  ],
  ["terraform/storage.tf", () => generateAwsStorage()],
  ["terraform/identity.tf", () => generateAwsIdentity()],
  ["terraform/compute.tf", () => generateAwsCompute()],
  ["terraform/secrets.tf", () => generateAwsSecrets()],
  ["terraform/dns.tf", () => generateAwsDns()],
  ["terraform/outputs.tf", (options) => generateAwsOutputs(options.dbEngine)],
  ["terraform/terraform.tfvars.example", () => generateAwsTfvarsExample()],
];

/** Generate every Terraform file for the AWS reference stack. */
export function generateAwsTerraformFiles(options: AwsTerraformOptions): TerraformFiles {
  const files: TerraformFiles = {};
  for (const [path, generate] of AWS_FILES) {
    files[path] = generate(options);
  }
  files["terraform/database.tf"] = generateAwsDatabase(options.dbEngine);
  files["terraform/README.md"] = generateAwsReadme(options.project);
  return files;
}
