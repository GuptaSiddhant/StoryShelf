/**
 * Terraform scaffolding for the AWS reference stack (enterprise default).
 *
 * Pure string builders — no runtime dependencies. Emitted by
 * `storyshelf server init` when the deploy target is `aws`, alongside the
 * standard `server.ts` / `worker.ts` / `package.json` files.
 *
 * Reference stack: S3 (storage) + SQS + DLQ (capture queue) + Postgres
 * (RDS default, Aurora DSQL option) + ECS Fargate app/worker + ALB +
 * Cognito (auth) + Secrets Manager + CloudWatch. VPC is created unless
 * `vpcId` is supplied; Route 53 + ACM apply only when `domainName` is set.
 */

/** Options for the AWS Terraform scaffold. */
export interface AwsTerraformOptions {
  /** Project slug, used as a name prefix for all resources. */
  project: string;
  /** AWS region, e.g. `us-east-1`. */
  region: string;
  /** Postgres engine: battle-tested RDS by default, serverless DSQL option. */
  dbEngine: "rds" | "dsql";
  /** Existing VPC id. Empty creates a new VPC. */
  vpcId?: string;
  /** Public domain for the ALB. Empty leaves the ALB HTTP-only. */
  domainName?: string;
  /** SAML metadata URL for Cognito federation (Entra/Okta). Empty skips it. */
  samlMetadataUrl?: string;
}

/** A generated file: relative path → contents. */
export type TerraformFiles = Record<string, string>;

/** Terraform CLI version floor for the generated modules. */
export const TERRAFORM_REQUIRED_VERSION = ">= 1.9";

function header(): string {
  return `# Generated by \`storyshelf server init --target aws\`. Do not edit by hand;\n# re-run the scaffold or edit the generator in @storyshelf/cli.\n\n`;
}

export function generateAwsVersions(): string {
  return `${header()}terraform {
  required_version = "${TERRAFORM_REQUIRED_VERSION}"

  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = ">= 5.60"
    }
  }
}
`;
}

export function generateAwsVariables(): string {
  return `${header()}variable "project" {
  description = "Project slug, used as a name prefix for all resources."
  type        = string
}

variable "region" {
  description = "AWS region for all resources."
  type        = string
  default     = "us-east-1"
}

variable "db_engine" {
  description = "Postgres engine: \\"rds\\" (Aurora/RDS, VPC-isolated) or \\"dsql\\" (serverless)."
  type        = string
  default     = "rds"

  validation {
    condition     = contains(["rds", "dsql"], var.db_engine)
    error_message = "db_engine must be \\"rds\\" or \\"dsql\\"."
  }
}

variable "vpc_id" {
  description = "Existing VPC id. Empty creates a new VPC."
  type        = string
  default     = ""
}

variable "domain_name" {
  description = "Public domain for the ALB (Route 53 + ACM). Empty leaves the ALB HTTP-only."
  type        = string
  default     = ""
}

variable "saml_metadata_url" {
  description = "SAML metadata URL for Cognito federation (Entra/Okta). Empty skips federation."
  type        = string
  default     = ""
}
`;
}

export function generateAwsVpc(): string {
  return `${header()}# VPC: created unless var.vpc_id points at an existing one.
resource "aws_vpc" "main" {
  count                = var.vpc_id == "" ? 1 : 0
  cidr_block           = "10.0.0.0/16"
  enable_dns_support   = true
  enable_dns_hostnames = true

  tags = { Name = "\${var.project}-vpc" }
}

locals {
  vpc_id = var.vpc_id != "" ? var.vpc_id : aws_vpc.main[0].id
}
`;
}

/** ALB + ECS security groups and private data-plane endpoints. */
