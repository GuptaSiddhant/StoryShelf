import { describe, expect, it } from "vitest";
import { generateAwsTerraformFiles } from "./terraform-aws.ts";
import { generateAzureTerraformFiles } from "./terraform-azure.ts";
import {
  TERRAFORM_REQUIRED_VERSION,
  terraformHeader,
  type TerraformFiles,
  type TerraformTarget,
} from "./terraform-common.ts";
import { generateGcpTerraformFiles } from "./terraform-gcp.ts";

const TARGETS: TerraformTarget[] = ["aws", "azure", "gcp"];

const GENERATE: Record<TerraformTarget, () => TerraformFiles> = {
  aws: () => generateAwsTerraformFiles({ project: "demo", region: "us-east-1" }),
  azure: () => generateAzureTerraformFiles({ project: "demo", location: "eastus" }),
  gcp: () => generateGcpTerraformFiles({ project: "demo", gcpProjectId: "p", location: "l" }),
};

function generated(target: TerraformTarget): TerraformFiles {
  return GENERATE[target]();
}

describe("terraformHeader", () => {
  it.each(TARGETS)("names the %s target and says not to edit by hand", (target) => {
    expect(terraformHeader(target)).toBe(
      `# Generated by \`storyshelf server init --target ${target}\`. Do not edit by hand;\n` +
        "# re-run the scaffold or edit the generator in @storyshelf/cli.\n\n",
    );
  });
});

describe("TERRAFORM_REQUIRED_VERSION", () => {
  it("is the floor of Terraform 1.9", () => {
    expect(TERRAFORM_REQUIRED_VERSION).toBe(">= 1.9");
  });

  it.each(TARGETS)("is what the %s versions.tf requires", (target) => {
    const versions = Object.entries(generated(target)).find(([path]) =>
      path.endsWith("versions.tf"),
    )?.[1];
    expect(versions).toContain(`required_version = "${TERRAFORM_REQUIRED_VERSION}"`);
  });
});

describe("the generators", () => {
  it.each(TARGETS)("start every %s .tf file with that target's header", (target) => {
    const tf = Object.entries(generated(target)).filter(([path]) => path.endsWith(".tf"));
    expect(tf.length).toBeGreaterThan(0);
    for (const [, contents] of tf) {
      expect(contents.startsWith(terraformHeader(target))).toBe(true);
    }
  });

  it("return a path-to-contents map under terraform/", () => {
    for (const target of TARGETS) {
      for (const [path, contents] of Object.entries(generated(target))) {
        expect(path.startsWith("terraform/")).toBe(true);
        expect(typeof contents).toBe("string");
      }
    }
  });
});
