export function generateGcpDns(): string {
  return `${header()}# Cloud DNS zone + app CNAME + domain mapping. Skipped entirely
# when var.domain_name is empty. Google issues the managed certificate
# automatically once the records resolve.
resource "google_dns_managed_zone" "main" {
  count       = var.domain_name == "" ? 0 : 1
  name        = "\${local.slug}-zone"
  dns_name    = "\${var.domain_name}."
  description = "\${var.project} app zone"
}

resource "google_dns_record_set" "app" {
  count        = var.domain_name == "" ? 0 : 1
  name         = "app.\${var.domain_name}."
  type         = "CNAME"
  ttl          = 300
  managed_zone = google_dns_managed_zone.main[0].name
  rrdatas      = ["\${trimsuffix(replace(google_cloud_run_v2_service.app.uri, "https://", ""), "/")}."]
}

resource "google_cloud_run_domain_mapping" "app" {
  count    = var.domain_name == "" ? 0 : 1
  location = var.location
  name     = "app.\${var.domain_name}"

  metadata {
    namespace = var.gcp_project_id
  }

  spec {
    route_name = google_cloud_run_v2_service.app.name
  }
}
`;
}

export function generateGcpOutputs(): string {
  return `${header()}# Outputs feed directly into the scaffolded server's env. Keys are
# a stable contract parsed by CI — do not rename (tests pin the set).
# Values are "" when the resource is not provisioned.
output "run_url" {
  value = google_cloud_run_v2_service.app.uri
}

output "gcs_bucket" {
  value = google_storage_bucket.storybook.name
}

output "database_url" {
  value     = "postgresql://shelfadmin:\${random_password.db.result}@\${google_sql_database_instance.main.public_ip_address}:5432/shelf?sslmode=require"
  sensitive = true
}

output "identity_tenant_id" {
  value = var.identity_tenant == "" ? "" : google_identity_platform_tenant.main[0].name
}
`;
}

