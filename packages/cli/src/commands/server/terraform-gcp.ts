const GCP_FILES: ReadonlyArray<readonly [string, (options: GcpTerraformOptions) => string]> = [
  ["terraform/versions.tf", () => generateGcpVersions()],
  ["terraform/variables.tf", () => generateGcpVariables()],
  ["terraform/main.tf", () => generateGcpMain()],
  ["terraform/compute.tf", () => generateGcpApp()],
  ["terraform/database.tf", () => generateGcpDatabase()],
  ["terraform/storage.tf", () => generateGcpStorage()],
  ["terraform/identity.tf", () => generateGcpIdentity()],
  ["terraform/secrets.tf", () => generateGcpSecrets()],
  ["terraform/dns.tf", () => generateGcpDns()],
  ["terraform/outputs.tf", () => generateGcpOutputs()],
  ["terraform/terraform.tfvars.example", () => generateGcpTfvarsExample()],
];

/** Generate every Terraform file for the GCP reference stack. */
export function generateGcpTerraformFiles(options: GcpTerraformOptions): TerraformFiles {
  const files: TerraformFiles = {};
  for (const [path, generate] of GCP_FILES) {
    files[path] = generate(options);
  }
  files["terraform/README.md"] = generateGcpReadme(options.project);
  return files;
}
