import { TERRAFORM_REQUIRED_VERSION } from "./terraform-aws.ts";

/**
 * Terraform scaffolding for the Google Cloud reference stack.
 *
 * Pure string builders — no runtime dependencies. Emitted by
 * `storyshelf server init` when the deploy target is `gcp`, alongside the
 * standard `src/index.ts` / `package.json` files.
 *
 * Reference stack: one Cloud Run service (serves the UI and consumes capture
 * jobs from the database queue) + GCS bucket (storybook bundles) +
 * Cloud SQL Postgres + Secret Manager + Identity Platform tenant (only
 * when `identity_tenant` is set) + Cloud DNS (only when `domain_name`
 * is set, with automatic managed TLS via the domain mapping).
 *
 * Output contract (stable keys, parsed by CI — see `GCP_TERRAFORM_OUTPUT_KEYS`):
 * keys are always present; values are `""` when the resource is not
 * provisioned for the optional inputs.
 */

/** Options for the GCP Terraform scaffold. */
export interface GcpTerraformOptions {
  /** Project slug, used as a name prefix for all resources. */
  project: string;
  /** Existing GCP project ID (APIs, billing, IAM live here). */
  gcpProjectId: string;
  /** GCP region, e.g. `us-central1`. */
  location: string;
  /** Public domain for the app. Empty leaves DNS out entirely. */
  domainName?: string;
  /** Identity Platform tenant display name. Empty skips identity. */
  identityTenant?: string;
}

/** A generated file: relative path → contents. */
export type TerraformFiles = Record<string, string>;

/**
 * Stable `terraform output -json` keys. CI (`live-cloud.yml`) parses these;
 * renaming a key is a breaking change — the unit tests pin this list.
 */
export const GCP_TERRAFORM_OUTPUT_KEYS: readonly string[] = [
  "database_url",
  "gcs_bucket",
  "identity_tenant_id",
  "run_url",
];

function header(): string {
  return `# Generated by \`storyshelf server init --target gcp\`. Do not edit by hand;\n# re-run the scaffold or edit the generator in @storyshelf/cli.\n\n`;
}

export function generateGcpVersions(): string {
  return `${header()}terraform {
  required_version = "${TERRAFORM_REQUIRED_VERSION}"

  required_providers {
    google = {
      source  = "hashicorp/google"
      version = ">= 6.0"
    }
    random = {
      source  = "hashicorp/random"
      version = ">= 3.0"
    }
  }
}

provider "google" {
  project = var.gcp_project_id
  region  = var.location
}
`;
}

