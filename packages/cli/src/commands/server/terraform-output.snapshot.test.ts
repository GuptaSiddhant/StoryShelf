/**
 * Pins every file the three Terraform generators write, for a spread of options: path, size and
 * SHA-256 of each. A refactor of the shared helpers can then be shown byte-identical; a change to
 * a template shows up here and is a decision, not an accident.
 */
import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import { generateAwsTerraformFiles } from "./terraform-aws.ts";
import { generateAzureTerraformFiles } from "./terraform-azure.ts";
import { generateGcpTerraformFiles } from "./terraform-gcp.ts";

function fingerprint(files: Record<string, string>): string[] {
  return Object.keys(files)
    .toSorted()
    .map((path) => {
      const contents = files[path] ?? "";
      const hash = createHash("sha256").update(contents).digest("hex");
      return `${path} ${Buffer.byteLength(contents)} ${hash}`;
    });
}

const CASES: Array<[string, () => Record<string, string>]> = [
  ["aws minimal", () => generateAwsTerraformFiles({ project: "demo", region: "us-east-1" })],
  [
    "aws full",
    () =>
      generateAwsTerraformFiles({
        project: "demo",
        region: "eu-west-1",
        vpcId: "vpc-123",
        domainName: "shelf.example.com",
        samlMetadataUrl: "https://idp.example.com/metadata.xml",
      }),
  ],
  ["azure minimal", () => generateAzureTerraformFiles({ project: "demo", location: "eastus" })],
  [
    "azure full",
    () =>
      generateAzureTerraformFiles({
        project: "demo",
        location: "westeurope",
        domainName: "shelf.example.com",
        entraTenantId: "11111111-2222-3333-4444-555555555555",
      }),
  ],
  [
    "gcp minimal",
    () =>
      generateGcpTerraformFiles({
        project: "demo",
        gcpProjectId: "my-proj",
        location: "us-central1",
      }),
  ],
  [
    "gcp full",
    () =>
      generateGcpTerraformFiles({
        project: "demo",
        gcpProjectId: "my-proj",
        location: "europe-west1",
        domainName: "shelf.example.com",
        identityTenant: "tenant-1",
      }),
  ],
];

describe("terraform generator output", () => {
  it.each(CASES)("is unchanged for %s", (_name, generate) => {
    expect(fingerprint(generate())).toMatchSnapshot();
  });

  it("starts every .tf file with the generated-by header for its own target", () => {
    for (const [target, files] of [
      ["aws", generateAwsTerraformFiles({ project: "demo", region: "us-east-1" })],
      ["azure", generateAzureTerraformFiles({ project: "demo", location: "eastus" })],
      ["gcp", generateGcpTerraformFiles({ project: "demo", gcpProjectId: "p", location: "l" })],
    ] as const) {
      const tf = Object.entries(files).filter(([path]) => path.endsWith(".tf"));
      expect(tf.length).toBeGreaterThan(0);
      for (const [path, contents] of tf) {
        expect(
          contents.startsWith(`# Generated by \`storyshelf server init --target ${target}\`.`),
          path,
        ).toBe(true);
      }
    }
  });
});
